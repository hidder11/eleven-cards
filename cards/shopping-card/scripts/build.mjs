import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const root=new URL('../',import.meta.url);
const theme=(await readFile(new URL('../../shared/card-theme.js',root),'utf8')).replace(/^export /gm,'');
const backgroundSource=(await Promise.all(['request.js','ui-button.js','ui-action-button.js','ui-card-background.js','card-background.js'].map(file=>readFile(new URL('../../shared/'+file,root),'utf8')))).map(source=>source.replace(/^import .*;\s*$/gm,'').replace(/^export /gm,'')).join('\n');
const source=await readFile(new URL('src/eleven-shopping-card.js',root),'utf8');
// Deliberately dependency-free: the source is already a closed, import-free IIFE.
if(/^import\s/m.test(source))throw Error('Standalone source must not contain imports');
await mkdir(new URL('dist/',root),{recursive:true});
const output=new URL('dist/eleven-shopping-card.js',root);
await writeFile(output,'/* Eleven Shopping Card — standalone; generated by scripts/build.mjs */\n'+'(()=>{\n'+theme+'\n'+backgroundSource+'\n'+source+'\n})();');
const result=spawnSync(process.execPath,['--check',fileURLToPath(output)],{encoding:'utf8'});
if(result.status!==0)throw Error(result.stderr);
console.log('Built '+fileURLToPath(output));
